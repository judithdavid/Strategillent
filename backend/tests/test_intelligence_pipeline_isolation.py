def add_evidence(db, external_id, industry_tags, domain):
    source = ResearchSource(
        source_name=f"{external_id}.example",
        source_type="test",
        url=f"https://{external_id.lower()}.example/source",
    )
    db.add(source)
    db.flush()

    record = Evidence(
        external_id=external_id,
        domain=domain,
        title=f"Evidence {external_id}",
        research_source_id=source.id,
        url=f"https://{external_id.lower()}.example/evidence",
        claim=f"Test claim for {external_id}",
        evidence_text=f"Test evidence text for {external_id}",
        strategic_implication="Test implication",
        confidence=3,
        relevance=3,
        tags=["test"],
        industries=industry_tags,
    )
    db.add(record)
    db.flush()
    return record


def add_dimension(db, external_id, name, industry_tags, domain):
    dimension = TransformationDimension(
        external_id=external_id,
        name=name,
        description=f"Test dimension: {name}",
        evidence_domains=[domain],
        candidate_initiatives=["Run a controlled pilot"],
        industries=industry_tags,
    )
    db.add(dimension)
    db.flush()
    return dimension



@pytest.mark.parametrize(
    ("industry", "expected_evidence_ids", "expected_dimension_ids"),
    [
        ("FinTech", {"FIN-E1", "ALL-E1"}, {"FIN-D1", "ALL-D1"}),
        ("EdTech", {"EDU-E1", "ALL-E1"}, {"EDU-D1", "ALL-D1"}),
        ("Healthcare", {"HLT-E1", "ALL-E1"}, {"HLT-D1", "ALL-D1"}),
        ("Unknown Industry", {"ALL-E1"}, {"ALL-D1"}),
    ],
)
def test_full_pipeline_preserves_industry_isolation(
    pipeline_db, industry, expected_evidence_ids, expected_dimension_ids
):
# def test_full_pipeline_preserves_industry_isolation(
#     pipeline_db, industry, expected_evidence, expected_dimension
# ):
    db = pipeline_db

    organisation = Organisation(
        name=f"Test organisation - {industry}",
        fictional=True,
        industry=industry,
        business_model=[],
        markets=[],
        products=[],
        challenges=[],
        goals=["Improve operational performance"],
        processes=[],
        technology=[],
        constraints=[],
    )
    db.add(organisation)

    # Industry-specific evidence and dimensions.
    add_evidence(db, "FIN-E1", ["FinTech"], "FRAUD")
    add_evidence(db, "EDU-E1", ["EdTech"], "LEARNING")
    add_evidence(db, "HLT-E1", ["Healthcare"], "PATIENT_SAFETY")

    add_dimension(db, "FIN-D1", "Fraud Risk", ["FinTech"], "FRAUD")
    add_dimension(db, "EDU-D1", "Learning Outcomes", ["EdTech"], "LEARNING")
    add_dimension(
        db, "HLT-D1", "Patient Safety", ["Healthcare"], "PATIENT_SAFETY"
    )

    # Explicitly universal evidence and dimension.
    add_evidence(db, "ALL-E1", ["*"], "GOVERNANCE")
    add_dimension(
        db, "ALL-D1", "Universal Governance", ["*"], "GOVERNANCE"
    )

    # Evidence without industry tags must never be selected.
    add_evidence(db, "UNTAGGED-E1", [], "FRAUD")
    db.commit()

    result = intelligence_service.run_intelligence_analysis(db, organisation)

    assert result["analysis_run"].status == "completed"

    # Every issue must use only evidence applicable to this industry.
    assert result["issues"]

    issue_evidence_ids = set()

    for issue in result["issues"]:
        assert issue.evidence

        evidence_ids = {item.external_id for item in issue.evidence}
        assert evidence_ids <= expected_evidence_ids
        issue_evidence_ids.update(evidence_ids)

    assert issue_evidence_ids == expected_evidence_ids

    # Opportunities must use applicable dimensions and evidence.
    assert result["opportunities"]

    opportunity_dimension_ids = set()
    opportunity_evidence_ids = set()

    for opportunity in result["opportunities"]:
        assert opportunity.transformation_dimension is not None
        assert opportunity.evidence

        dimension_id = opportunity.transformation_dimension.external_id
        evidence_ids = {item.external_id for item in opportunity.evidence}

        assert dimension_id in expected_dimension_ids
        assert evidence_ids <= expected_evidence_ids

        opportunity_dimension_ids.add(dimension_id)
        opportunity_evidence_ids.update(evidence_ids)

    assert opportunity_dimension_ids == expected_dimension_ids
    assert opportunity_evidence_ids == expected_evidence_ids

    # Initiatives must be linked to the generated opportunities and retain evidence context.
    assert result["initiatives"]

    opportunity_ids = {item.id for item in result["opportunities"]}

    for initiative in result["initiatives"]:
        assert initiative.opportunity_id in opportunity_ids

        linked_opportunity = next(
            item for item in result["opportunities"]
            if item.id == initiative.opportunity_id
        )

        for evidence in linked_opportunity.evidence:
            assert evidence.external_id in initiative.description


def test_unknown_industry_with_no_universal_data_produces_no_recommendations(
    pipeline_db,
):
    db = pipeline_db

    organisation = Organisation(
        name="Unknown industry without universal data",
        fictional=True,
        industry="Unclassified Sector",
        business_model=[],
        markets=[],
        products=[],
        challenges=[],
        goals=[],
        processes=[],
        technology=[],
        constraints=[],
    )
    db.add(organisation)

    add_evidence(db, "FIN-ONLY-E1", ["FinTech"], "FRAUD")
    add_dimension(db, "FIN-ONLY-D1", "Fraud Risk", ["FinTech"], "FRAUD")
    db.commit()

    result = intelligence_service.run_intelligence_analysis(db, organisation)

    assert result["issues"] == []
    assert result["opportunities"] == []
    assert result["initiatives"] == []

    # The analysis run can complete even when no applicable recommendations exist.
    assert result["analysis_run"].status == "completed"
