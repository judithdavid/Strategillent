from fastapi.testclient import TestClient

from app.main import app
from app.services import intelligence_service


def fake_analyse_dimension(dimension, evidence, organisation):
    return {
        "title": f"Test issue: {dimension.name}",
        "description": "A test strategic issue supported by evidence.",
        "severity": 8,
        "evidence": evidence,
    }



def fake_generate_opportunity(
    dimension,
    issue,
    organisation,
    evidence_records=None,
):
    evidence_records = evidence_records or []

    return {
        "title": f"Test opportunity: {issue.title}",
        "description": "A test opportunity supported by evidence.",
        "rationale": "Generated by the test fixture.",
        "business_impact": 8.0,
        "feasibility": 7.0,
        "urgency": 8.0,
        "strategic_alignment": 8.0,
        "evidence_confidence": 8.0,
        "evidence_ids": [
            item.external_id
            for item in evidence_records
            if getattr(item, "external_id", None)
        ],
        "model_used": "test-model",
        "status": "completed",
    }



def test_get_intelligence_before_or_after_run():
    with TestClient(app) as client:
        response = client.get("/api/intelligence/1")
        assert response.status_code in [200, 404]


def test_run_intelligence(monkeypatch):
    monkeypatch.setattr(
        intelligence_service,
        "analyse_dimension",
        fake_analyse_dimension,
    )
    monkeypatch.setattr(
        intelligence_service,
        "generate_opportunity",
        fake_generate_opportunity,
    )

    with TestClient(app) as client:
        response = client.post("/api/intelligence/1/run")

    assert response.status_code == 200, response.text

    data = response.json()

    assert "analysis_run_id" in data
    assert "organisation_id" in data
    assert "opportunities" in data
    assert "initiatives" in data

    assert isinstance(data["opportunities"], list)
    assert isinstance(data["initiatives"], list)

    assert len(data["opportunities"]) > 0
    assert len(data["initiatives"]) > 0


def test_intelligence_creates_expected_structure(monkeypatch):
    monkeypatch.setattr(
        intelligence_service,
        "analyse_dimension",
        fake_analyse_dimension,
    )
    monkeypatch.setattr(
        intelligence_service,
        "generate_opportunity",
        fake_generate_opportunity,
    )

    with TestClient(app) as client:
        run_response = client.post("/api/intelligence/1/run")
        assert run_response.status_code == 200, run_response.text

        response = client.get("/api/intelligence/1")

    assert response.status_code == 200, response.text

    data = response.json()

    assert "analysis_run_id" in data
    assert "organisation_id" in data
    assert "opportunities" in data
    assert "initiatives" in data
